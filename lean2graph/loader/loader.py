from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import tarfile
import zipfile
import tempfile
from dataclasses import dataclass
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.parse import urlparse


ARCHIVE_SUFFIXES = (".zip", ".tar.gz", ".tgz", ".tar")


@dataclass
class LoadedInput:
    root: Path
    input_kind: str
    source: str
    cleanup: bool = False
    temporary: TemporaryDirectory[str] | None = None

    def close(self) -> None:
        if self.cleanup and self.temporary is not None:
            self.temporary.cleanup()


class LoaderError(RuntimeError):
    pass


class ProjectLoader:
    def __init__(
        self,
        *,
        max_archive_bytes: int = 2 * 1024**3,
        max_files: int = 100_000,
    ) -> None:
        self.max_archive_bytes = max_archive_bytes
        self.max_files = max_files

    def load(self, input_value: str, rev: str | None = None) -> LoadedInput:
        path = Path(input_value).expanduser()
        if path.exists():
            if path.is_dir():
                root = self.find_project_root(path)
                if root is None:
                    raise LoaderError(f"Lean project root not found under {path}")
                return LoadedInput(root, "directory", str(path.resolve()))
            if path.is_file() and path.suffix.lower() == ".lean":
                return self._load_lean_file(path)
            if path.is_file() and self._is_archive(path):
                return self._load_archive(path)
            raise LoaderError(f"Unsupported input: {path}")
        if self._is_git_url(input_value):
            return self._clone_git(input_value, rev)
        raise LoaderError(f"Input does not exist and is not a git URL: {input_value}")

    def find_project_root(self, path: Path) -> Path | None:
        candidates: list[Path] = []
        current = path.resolve()
        for candidate in (current, *current.parents):
            if (candidate / "lakefile.lean").is_file() or (
                candidate / "lakefile.toml"
            ).is_file() or (candidate / "lean-toolchain").is_file():
                candidates.append(candidate)
        if candidates:
            candidates.sort(key=lambda p: len(p.parts))
            return candidates[0]

        nested = [
            p
            for p in current.iterdir()
            if p.is_dir() and not p.name.startswith(".")
        ]
        if len(nested) == 1:
            nested_root = self.find_project_root(nested[0])
            if nested_root is not None:
                return nested_root

        lean_files = list(current.rglob("*.lean"))
        if lean_files:
            if list(current.glob("*.lean")):
                return current
            containing_dirs = {
                lean_file.parent.resolve() for lean_file in lean_files
            }
            if len(containing_dirs) == 1:
                return containing_dirs.pop()
            nested = [
                p
                for p in current.iterdir()
                if p.is_dir() and not p.name.startswith(".")
            ]
            if len(nested) == 1:
                nested_root = self.find_project_root(nested[0])
                if nested_root is not None:
                    return nested_root
            return current

        if path.name and path.is_dir():
            nested = [p for p in path.iterdir() if p.is_dir() and not p.name.startswith(".")]
            if len(nested) == 1:
                nested_root = self.find_project_root(nested[0])
                if nested_root is not None:
                    return nested_root
        return None

    def create_synthetic_project(self, root: Path) -> bool:
        if (root / "lakefile.toml").is_file():
            return False
        lakefile_path = root / "lakefile.lean"
        lakefile = lakefile_path.read_text(encoding="utf-8") if lakefile_path.is_file() else None
        legacy_lakefile = (
            "import Lake\nopen Lake DSL\n\npackage synthetic\n\nlean_lib Synthetic\n"
        )
        if lakefile is not None and not (
            lakefile.startswith("-- Generated by lean2graph.\n")
            or lakefile in {
                legacy_lakefile,
                legacy_lakefile
                + '\nrequire mathlib from git\n  "https://github.com/leanprover-community/mathlib4.git"\n',
            }
        ):
            return False
        lean_files = sorted(
            path
            for path in root.rglob("*.lean")
            if not any(part in {".lake", ".git"} for part in path.relative_to(root).parts)
            and path.name != "lakefile.lean"
        )
        if not lean_files:
            return False
        lean_sources = "\n".join(
            p.read_text(encoding="utf-8", errors="replace") for p in lean_files
        )
        roots = [
            ".".join(path.relative_to(root).with_suffix("").parts)
            for path in lean_files
        ]
        root_list = ", ".join(f"`{module}" for module in roots)
        generated_lakefile = (
            "-- Generated by lean2graph.\n"
            "import Lake\nopen Lake DSL\n\n"
            "package synthetic\n\n"
            "@[default_target]\n"
            "lean_lib Synthetic where\n"
            f"  roots := #[{root_list}]\n"
        )
        if "import Mathlib" in lean_sources or "\nopen scoped Mathlib" in lean_sources:
            generated_lakefile += (
                '\nrequire mathlib from git\n  "https://github.com/leanprover-community/mathlib4.git"\n'
            )
        lakefile_path.write_text(generated_lakefile, encoding="utf-8")
        return True

    def project_id(self, root: Path) -> str:
        digest = hashlib.sha256()
        for path in sorted(p for p in root.rglob("*") if p.is_file()):
            if any(part in {".lake", ".git", "__pycache__"} for part in path.parts):
                continue
            try:
                rel = path.relative_to(root).as_posix().encode("utf-8")
                content = path.read_bytes()
            except (OSError, ValueError):
                continue
            digest.update(len(rel).to_bytes(8, "big"))
            digest.update(rel)
            digest.update(content)
        return f"project-{digest.hexdigest()[:16]}"

    def _is_git_url(self, value: str) -> bool:
        parsed = urlparse(value)
        return value.startswith("git@") or parsed.scheme in {"http", "https", "ssh", "git"}

    def _load_lean_file(self, source: Path) -> LoadedInput:
        temporary = TemporaryDirectory(prefix="lean2graph-file-")
        destination = Path(temporary.name)
        target = destination / source.name
        try:
            shutil.copy2(source, target)
            return LoadedInput(
                destination,
                "lean_file",
                str(source.resolve()),
                cleanup=True,
                temporary=temporary,
            )
        except Exception:
            temporary.cleanup()
            raise

    def _is_archive(self, path: Path) -> bool:
        name = path.name.lower()
        return name.endswith(ARCHIVE_SUFFIXES)

    def _load_archive(self, archive: Path) -> LoadedInput:
        size = archive.stat().st_size
        if size > self.max_archive_bytes:
            raise LoaderError(
                f"Archive is too large: {size} bytes (limit {self.max_archive_bytes})"
            )
        temporary = TemporaryDirectory(prefix="lean2graph-")
        destination = Path(temporary.name)
        try:
            if zipfile.is_zipfile(archive):
                self._safe_extract_zip(archive, destination)
            elif tarfile.is_tarfile(archive):
                self._safe_extract_tar(archive, destination)
            else:
                raise LoaderError("Unsupported or invalid archive")
            root = self.find_project_root(destination)
            if root is None:
                raise LoaderError("Archive has no recognizable Lean project")
            return LoadedInput(
                root,
                "archive",
                str(archive.resolve()),
                cleanup=True,
                temporary=temporary,
            )
        except Exception:
            temporary.cleanup()
            raise

    def _ensure_safe_destination(self, destination: Path, name: str) -> Path:
        target = (destination / name).resolve()
        if destination.resolve() not in target.parents and target != destination.resolve():
            raise LoaderError(f"Unsafe archive path traversal: {name}")
        return target

    def _safe_extract_zip(self, archive: Path, destination: Path) -> None:
        count = 0
        total = 0
        with zipfile.ZipFile(archive) as zf:
            for info in zf.infolist():
                count += 1
                if count > self.max_files:
                    raise LoaderError(f"Archive contains more than {self.max_files} files")
                mode = (info.external_attr >> 16) & 0xFFFF
                if mode & 0o170000 == 0o120000:
                    raise LoaderError(f"Symbolic links are not allowed: {info.filename}")
                total += info.file_size
                if total > self.max_archive_bytes:
                    raise LoaderError("Uncompressed archive exceeds configured size limit")
                target = self._ensure_safe_destination(destination, info.filename)
                if info.is_dir():
                    target.mkdir(parents=True, exist_ok=True)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with zf.open(info) as src, target.open("wb") as dst:
                        shutil.copyfileobj(src, dst, length=1024 * 1024)

    def _safe_extract_tar(self, archive: Path, destination: Path) -> None:
        count = 0
        total = 0
        with tarfile.open(archive, "r:*") as tf:
            for member in tf:
                count += 1
                if count > self.max_files:
                    raise LoaderError(f"Archive contains more than {self.max_files} files")
                if member.issym() or member.islnk():
                    raise LoaderError(f"Links are not allowed in archive: {member.name}")
                if not (member.isfile() or member.isdir()):
                    raise LoaderError(f"Unsupported archive member: {member.name}")
                total += member.size
                if total > self.max_archive_bytes:
                    raise LoaderError("Uncompressed archive exceeds configured size limit")
                target = self._ensure_safe_destination(destination, member.name)
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    source = tf.extractfile(member)
                    if source is None:
                        raise LoaderError(f"Cannot read archive member: {member.name}")
                    with source, target.open("wb") as dst:
                        shutil.copyfileobj(source, dst, length=1024 * 1024)

    def _clone_git(self, url: str, rev: str | None) -> LoadedInput:
        temporary = TemporaryDirectory(prefix="lean2graph-git-")
        destination = Path(temporary.name) / "repo"
        try:
            subprocess.run(
                ["git", "clone", "--depth", "1", url, str(destination)],
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            if rev:
                subprocess.run(
                    ["git", "-C", str(destination), "fetch", "--depth", "1", "origin", rev],
                    check=True,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                )
                subprocess.run(
                    ["git", "-C", str(destination), "checkout", "--detach", rev],
                    check=True,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                )
            root = self.find_project_root(destination)
            if root is None:
                raise LoaderError("Cloned repository has no recognizable Lean project")
            return LoadedInput(
                root,
                "git",
                url,
                cleanup=True,
                temporary=temporary,
            )
        except subprocess.CalledProcessError as exc:
            temporary.cleanup()
            stderr = exc.stderr.strip() if exc.stderr else "git clone failed"
            raise LoaderError(stderr) from exc
        except Exception:
            temporary.cleanup()
            raise
